"""README 대표 그림: 설계기준 보고서 5절 표(같은 관망을 기준별로 설계한 결과)를 막대그래프로.

입력은 engine.report 가 쓴 보고서 Markdown 이라 DB 없이 다시 그릴 수 있다.
    py -3 docs/make_standards_figure.py docs/SYN01_design_criteria_report.md docs/SYN01_standards.png
"""
import re
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

LABELS = {
    "KDS_61_40_00_20251001": "Korea\nKDS 61 40 00 (2025)",
    "TSS_WW_2026": "US\nTen States (2026)",
    "JP_YOKOHAMA_SEKKEI_202604": "Japan\nYokohama (2026)",
    "CPHEEO_SEW_2013": "India\nCPHEEO (2013)",
    "CO_RAS_0330_2017_COMP2021": "Colombia\nRAS 0330 (2021)",
    "GB_DCG_V2_3_20231111": "UK (England)\nWater UK DCG (2023)",
}
NUMBER_WORDS = {2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight"}

# 5절 표 열: 기준 | 굴착 지표 | 최대 관경 | 최대 매설깊이 | 추가 맨홀 | ...
PANELS = [
    ("Excavation index (m²)", 1, "{:,.0f}"),
    ("Max burial depth (m)", 3, "{:.2f}"),
    ("Max pipe diameter (mm)", 2, "{:,.0f}"),
    ("Extra manholes", 4, "{:,.0f}"),
]


def read_results(report_path):
    text = open(report_path, encoding="utf-8").read()
    section = text.split("## 5. ", 1)[1].split("\n## ", 1)[0].split("\n### ", 1)[0]
    rows = []
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 5 or cells[0] not in LABELS:
            continue
        rows.append((cells[0], [float(c) for c in cells[1:5]]))
    if not rows:
        sys.exit(f"{report_path}: 5절 결과 표를 찾지 못함")
    return rows


def main(report_path, out_path):
    rows = read_results(report_path)
    n = len(rows)
    exc = [v[0] for _, v in rows]
    dep = [v[2] for _, v in rows]
    exc_pct = round((max(exc) / min(exc) - 1) * 100)
    dep_x = max(dep) / min(dep)

    fig, axes = plt.subplots(1, len(PANELS), figsize=(19.5, 1.2 + 0.85 * n), dpi=100)
    fig.patch.set_facecolor("#fcfcfa")
    ys = list(range(n))[::-1]
    for i, (ax, (title, col, fmt)) in enumerate(zip(axes, PANELS)):
        vals = [v[col - 1] for _, v in rows]
        ax.set_facecolor("#fcfcfa")
        ax.barh(ys, vals, height=0.5, color="#2b7bd6")
        top = max(vals)
        for y, v in zip(ys, vals):
            ax.text(v + top * 0.03, y, fmt.format(v), va="center", fontsize=13)
        ax.set_xlim(0, top * 1.25)
        ax.set_title(title, loc="left", fontsize=15, pad=10)
        ax.set_xticks([])
        ax.set_yticks(ys)
        ax.set_yticklabels([LABELS[s] for s, _ in rows] if i == 0 else [], fontsize=13)
        ax.tick_params(axis="y", length=0)
        for side in ("top", "right", "bottom"):
            ax.spines[side].set_visible(False)
        ax.spines["left"].set_color("#dddddd")

    word = NUMBER_WORDS.get(n, str(n))
    fig.suptitle(f"Same sewer network (SYN01), designed under {word} national standards",
                 x=0.01, ha="left", fontsize=18, fontweight="bold")
    fig.text(0.01, 0.015,
             "Generated by engine.report from each standard's own clauses. "
             f"Excavation varies {exc_pct}% and maximum depth {dep_x:.1f}x for the same network.",
             fontsize=13, color="#555555")
    fig.subplots_adjust(left=0.12, right=0.99, top=0.80, bottom=0.10, wspace=0.12)
    fig.savefig(out_path, facecolor=fig.get_facecolor())
    print(f"{out_path}: {n}개 기준, 굴착 {exc_pct}% 차이, 최대깊이 {dep_x:.2f}배")


if __name__ == "__main__":
    main(*sys.argv[1:3])
